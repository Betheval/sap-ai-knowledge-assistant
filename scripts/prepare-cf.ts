/**
 * Turns the output of `npm run build` into Cloud Foundry modules (ADR 0019):
 *
 * - gen/srv: a production-only package.json (no workspaces, dev dependencies or
 *   development scripts) and a lockfile resolved for it;
 * - gen/pg: the CAP deployer also applies the SQL-managed retrieval schema;
 * - app/router/resources: the built UI, served by the approuter.
 */
import { spawnSync } from 'node:child_process'
import { copyFileSync, cpSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const root = path.join(__dirname, '..')
const at = (...p: string[]) => path.join(root, ...p)
const readJson = (file: string) => JSON.parse(readFileSync(file, 'utf8'))
const writeJson = (file: string, data: unknown) => writeFileSync(file, JSON.stringify(data, null, 2) + '\n')

function run(cwd: string, command: string, args: string[]) {
  const result = spawnSync(command, args, { cwd, stdio: 'inherit' })
  if (result.status !== 0) throw new Error(`${command} ${args.join(' ')} failed in ${cwd}`)
}

// --- gen/srv: production package
const srv = at('gen', 'srv')
const pkg = readJson(path.join(srv, 'package.json'))
writeJson(path.join(srv, 'package.json'), {
  name: pkg.name,
  version: pkg.version,
  description: pkg.description,
  license: pkg.license,
  private: true,
  engines: { node: '^22.0.0 || ^24.0.0' },
  scripts: { start: 'cds-serve' },
  imports: pkg.imports,
  dependencies: pkg.dependencies,
  cds: pkg.cds,
})
// Start from the project's lockfile, so the deployed versions are exactly the tested ones;
// npm only drops the entries of development dependencies and workspaces
copyFileSync(at('package-lock.json'), path.join(srv, 'package-lock.json'))
run(srv, 'npm', [
  'install',
  '--package-lock-only',
  '--omit=dev',
  '--ignore-scripts',
  '--no-audit',
  '--no-fund',
])

// --- gen/pg: deploy the CDS schema, then the retrieval columns and indexes
const pg = at('gen', 'pg')
copyFileSync(at('db', 'postgres', 'retrieval-schema.sql'), path.join(pg, 'db', 'retrieval-schema.sql'))
copyFileSync(
  path.join(srv, 'srv', 'lib', 'adapters', 'postgres', 'retrieval-schema.js'),
  path.join(pg, 'retrieval-schema.js'),
)
writeFileSync(
  path.join(pg, 'apply-retrieval-schema.js'),
  `// Generated by scripts/prepare-cf.ts: runs after cds-deploy in the deployer task
const cds = require('@sap/cds')
const path = require('node:path')
const { applyRetrievalSchema } = require('./retrieval-schema')

cds.connect.to('db')
  .then((db) => applyRetrievalSchema(db, path.join(__dirname, 'db', 'retrieval-schema.sql')))
  .then((count) => { console.log('Applied ' + count + ' retrieval schema statements'); process.exit(0) })
  .catch((error) => { console.error(error); process.exit(1) })
`,
)
const deployer = readJson(path.join(pg, 'package.json'))
deployer.scripts = { start: 'cds-deploy && node apply-retrieval-schema.js' }
deployer.engines = { node: '^22.0.0 || ^24.0.0' }
writeJson(path.join(pg, 'package.json'), deployer)

// --- approuter: the built UI
const resources = at('app', 'router', 'resources')
rmSync(resources, { recursive: true, force: true })
cpSync(at('app', 'assistant', 'dist'), resources, { recursive: true })

console.log('Prepared gen/srv, gen/pg and app/router for Cloud Foundry')
